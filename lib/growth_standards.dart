/// Get LMS for a specific age using linear interpolation
LMSParameters? getLMSForAge(List<LMSDataPoint> dataset, double ageMonths) {
  if (dataset.isEmpty) return null;

  if (ageMonths < dataset.first.ageMonths) return LMSParameters(
    l: dataset.first.l,
    m: dataset.first.m,
    s: dataset.first.s,
  );

  if (ageMonths > dataset.last.ageMonths) return LMSParameters(
    l: dataset.last.l,
    m: dataset.last.m,
    s: dataset.last.s,
  );

  for (int i = 0; i < dataset.length - 1; i++) {
    final p1 = dataset[i];
    final p2 = dataset[i + 1];

    if (ageMonths >= p1.ageMonths && ageMonths <= p2.ageMonths) {
      final fraction = (ageMonths - p1.ageMonths) / (p2.ageMonths - p1.ageMonths);
      return LMSParameters(
        l: p1.l + (p2.l - p1.l) * fraction,
        m: p1.m + (p2.m - p1.m) * fraction,
        s: p1.s + (p2.s - p1.s) * fraction,
      );
    }
  }

  return null;
}

/// Get relevant dataset based on sex, measure type, and age.
///
/// Selection: WHO Child Growth Standards for weight (0-60 months) and head
/// circumference (0-60 months); CDC Growth Reference 2000 for weight
/// (60-240 months) and BMI (24-240 months, per convention BMI is only
/// assessed from 2 years). Head circumference has no standard reference
/// beyond 60 months, so an empty dataset is returned past that age.
Map<String, dynamic> getRelevantDataset(
  String sex,
  String measureType,
  double ageMonths,
) {
  const whoName = 'WHO Child Growth Standards (2006)';
  const cdcName = 'CDC Growth Reference (2000)';

  if (measureType == 'weight') {
    final isWHO = ageMonths < 60;
    if (sex == 'M') {
      return {
        'dataset': isWHO ? whoBoyWeight : cdcBoyWeight,
        'standardName': isWHO ? whoName : cdcName,
      };
    } else {
      return {
        'dataset': isWHO ? whoGirlWeight : cdcGirlWeight,
        'standardName': isWHO ? whoName : cdcName,
      };
    }
  }

  if (measureType == 'bmi') {
    if (ageMonths < 24) {
      return {'dataset': <LMSDataPoint>[], 'standardName': cdcName};
    }
    return {
      'dataset': sex == 'M' ? cdcBoyBMI : cdcGirlBMI,
      'standardName': cdcName,
    };
  }

  if (measureType == 'hc') {
    if (ageMonths > 60) {
      return {'dataset': <LMSDataPoint>[], 'standardName': whoName};
    }
    return {
      'dataset': sex == 'M' ? whoBoyHC : whoGirlHC,
      'standardName': whoName,
    };
  }

  // Fallback for other measure types
  return {
    'dataset': <LMSDataPoint>[],
    'standardName': 'Unknown',
  };
}
